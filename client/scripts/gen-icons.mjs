/**
 * Builds src/components/phosphor.jsx: only the Phosphor icons the app imports in src/components/icons.jsx, and only the
 * weights it uses (regular, fill, duotone). The npm package ships six weights per icon in the bundle; this keeps three.
 * Run after adding an icon to icons.jsx:  node scripts/gen-icons.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const require = createRequire(import.meta.url);
const WEIGHTS = ['regular', 'fill', 'duotone'];

const src = fs.readFileSync(path.join(root, 'src/components/icons.jsx'), 'utf8');
const m = src.match(/import \{([^}]+)\} from '(?:@phosphor-icons\/react|\.\/phosphor\.jsx)';/);
if (!m) throw new Error('icons.jsx: icon import not found');
const names = m[1].split(',').map((s) => s.trim().split(/\s+as\s+/)[0]).filter(Boolean);

const defsDir = path.join(path.dirname(require.resolve('@phosphor-icons/react')), 'defs');
const out = {};
for (const name of names) {
  const mod = await import(path.join(defsDir, `${name}.mjs`));
  const map = mod.default;
  out[name] = {};
  for (const w of WEIGHTS) {
    const frag = map.get(w);
    const kids = [].concat(frag.props.children || []);
    out[name][w] = kids.filter(Boolean).map((el) => [el.type, el.props]);
  }
}

const body = `// Generated by scripts/gen-icons.mjs from @phosphor-icons/react (MIT). Do not edit by hand.
import { createElement as h, forwardRef } from 'react';

const DATA = ${JSON.stringify(out)};

function make(name) {
  const Icon = forwardRef(function Icon({ size = '1em', weight = 'regular', color = 'currentColor', mirrored = false, alt, children, ...rest }, ref) {
    const d = DATA[name][weight] || DATA[name].regular;
    return h('svg', { ref, xmlns: 'http://www.w3.org/2000/svg', width: size, height: size, fill: color, viewBox: '0 0 256 256', transform: mirrored ? 'scale(-1, 1)' : undefined, ...rest },
      alt ? h('title', null, alt) : null, children, ...d.map(([t, p], i) => h(t, { key: i, ...p })));
  });
  Icon.displayName = name;
  return Icon;
}

${names.map((n) => `export const ${n} = make('${n}');`).join('\n')}
`;
fs.writeFileSync(path.join(root, 'src/components/phosphor.jsx'), body);
console.log(`phosphor.jsx: ${names.length} icons × ${WEIGHTS.length} weights, ${Math.round(body.length / 1024)} KB`);
